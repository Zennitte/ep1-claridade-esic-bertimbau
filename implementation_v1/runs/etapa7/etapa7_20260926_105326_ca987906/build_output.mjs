import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import { FileBlob, SpreadsheetFile } from '@oai/artifact-tool';
const root='C:/Users/KABUM/Documents/BERT- Fine';
const runId='etapa7_20260926_105326_ca987906';
const runDir=`${root}/runs/etapa7/${runId}`;
const input=`${root}/test1.xlsx`;
const output=`${root}/outputs/${runId}/test1_predito.xlsx`;
const result=JSON.parse(await fs.readFile(`${runDir}/inference.json`,'utf8'));
if(result.n_rows!==900 || result.test_labels_used!==false) throw new Error('Metadados da inferência inválidos');
const wb=await SpreadsheetFile.importXlsx(await FileBlob.load(input));
const sheet=wb.worksheets.getItem('test1');
const original=sheet.getRange('A1:A901').values;
const headers=sheet.getRange('A1:B1').values[0];
const blankTarget=sheet.getRange('B2:B901').values;
if(JSON.stringify(headers)!==JSON.stringify(['resp_text','clarity'])) throw new Error('Cabeçalhos diferentes do previsto');
if(original.length!==901 || blankTarget.length!==900 || blankTarget.some(row=>row[0]!==null && row[0]!==undefined && row[0]!=='')) throw new Error('Estrutura/coluna original inesperada');
if(result.predictions.length!==900 || result.predictions.some(p=>!['c1','c234','c5'].includes(p))) throw new Error('Predições inválidas');
sheet.getRange('B2:B901').values=result.predictions.map(p=>[p]);
wb.recalculate();
const file=await SpreadsheetFile.exportXlsx(wb);
await file.save(output);
const reopened=await SpreadsheetFile.importXlsx(await FileBlob.load(output));
const verifySheet=reopened.worksheets.getItem('test1');
const afterA=verifySheet.getRange('A1:A901').values;
const afterB=verifySheet.getRange('B1:B901').values;
const workbookMeta=JSON.parse((await reopened.inspect({kind:'workbook',include:'id,sheets'})).ndjson);
const expectedB=[['clarity'],...result.predictions.map(p=>[p])];
if(JSON.stringify(afterA)!==JSON.stringify(original)) throw new Error('Coluna resp_text alterada');
if(JSON.stringify(afterB)!==JSON.stringify(expectedB)) throw new Error('Valores exportados diferem das previsões');
if(workbookMeta.sheets!==1) throw new Error('Número de abas inesperado');
const preview=await reopened.render({sheetName:'test1',range:'A1:B18',scale:1,format:'png'});
await fs.writeFile(`${runDir}/final_preview.png`,Buffer.from(await preview.arrayBuffer()));
const bytes=await fs.readFile(output);
const check={run_id:runId,output_file:output,output_sha256:crypto.createHash('sha256').update(bytes).digest('hex'),sheets:workbookMeta.sheets,sheet_name:'test1',rows:afterA.length-1,columns:headers,resp_text_unchanged:true,prediction_cells_filled:afterB.slice(1).filter(r=>r[0]!==null&&r[0]!==undefined&&r[0]!=='').length,prediction_classes:[...new Set(afterB.slice(1).map(r=>r[0]))].sort(),sample_first_5:afterB.slice(1,6).map(r=>r[0]),output_size_bytes:bytes.length};
await fs.writeFile(`${runDir}/structural_check.json`,JSON.stringify(check,null,2),'utf8');
console.log(JSON.stringify(check,null,2));
